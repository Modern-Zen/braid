// pnpm patches:bundle
//
// Bundles the recorded patch series (scripts/scripted-patches/<intent>/<strategy>/) into
// apps/worker/src/generated/patches.ts so scripted Channels can replay them from the Worker.
// Each series: 000N-*.patch (git format-patch), meta.json, logbook.md, result.json.
import { existsSync, mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const src = join(root, "scripts", "scripted-patches");
const out = join(root, "apps", "worker", "src", "generated", "patches.ts");

interface Meta {
  intent: string;
  strategy: string;
  agent: string;
  model: string;
  base?: string;
  lines?: string[];
  turns?: number;
  durationMs?: number;
  costUsd?: number | null;
  commits?: Array<{ file: string; subject?: string; delaySec?: [number, number] }>;
}

const series: Record<string, unknown> = {};
const resolutions: Record<string, unknown> = {};

const dirs = (p: string) => (existsSync(p) ? readdirSync(p).filter((n) => statSync(join(p, n)).isDirectory()) : []);

for (const intent of dirs(src)) {
  for (const strategy of dirs(join(src, intent))) {
    const dir = join(src, intent, strategy);
    const metaPath = join(dir, "meta.json");
    if (!existsSync(metaPath)) continue;
    const meta = JSON.parse(readFileSync(metaPath, "utf8")) as Meta;
    const patchFiles = readdirSync(dir).filter((n) => /^\d{4}-.*\.patch$/.test(n)).sort();
    const delays = new Map((meta.commits ?? []).map((c) => [c.file, c.delaySec]));
    series[`${intent}/${strategy}`] = {
      intent,
      strategy,
      agent: meta.agent,
      model: meta.model,
      base: meta.base ?? null,
      lines: meta.lines ?? [],
      turns: meta.turns ?? null,
      durationMs: meta.durationMs ?? null,
      costUsd: meta.costUsd ?? null,
      logbook: existsSync(join(dir, "logbook.md")) ? readFileSync(join(dir, "logbook.md"), "utf8") : "",
      result: existsSync(join(dir, "result.json")) ? JSON.parse(readFileSync(join(dir, "result.json"), "utf8")) : null,
      commits: patchFiles.map((file) => ({ file, patch: readFileSync(join(dir, file), "utf8"), delaySec: delays.get(file) ?? null })),
    };
  }
  // Optional merge resolutions for Confluence, e.g. refactor-gauge/RESOLUTION.md + resolution-*.patch
  const resDir = join(src, intent);
  for (const file of readdirSync(resDir).filter((n) => /^resolution.*\.patch$/i.test(n))) {
    resolutions[`${intent}/${file}`] = {
      intent,
      file,
      patch: readFileSync(join(resDir, file), "utf8"),
      notes: existsSync(join(resDir, "RESOLUTION.md")) ? readFileSync(join(resDir, "RESOLUTION.md"), "utf8") : "",
    };
  }
}

mkdirSync(dirname(out), { recursive: true });
writeFileSync(
  out,
  `// GENERATED by \`pnpm patches:bundle\` from scripts/scripted-patches. Do not edit.
import type { RecordedResolution, RecordedSeries } from "../agents/adapters/recorded.ts";

export const SERIES: Record<string, RecordedSeries> = ${JSON.stringify(series, null, 2)};

export const RESOLUTIONS: Record<string, RecordedResolution> = ${JSON.stringify(resolutions, null, 2)};
`,
);
console.log(`patches:bundle  ${Object.keys(series).length} series, ${Object.keys(resolutions).length} resolutions → apps/worker/src/generated/patches.ts`);
