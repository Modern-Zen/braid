// pnpm design:sync
//
// Copies the Claude Design export (repo root, read-only) into the UI app:
//   headwaters-tokens.css → apps/ui/src/styles/headwaters-tokens.css  (font url()s rewritten)
//   fonts/*               → apps/ui/public/fonts/
//   assets/*              → apps/ui/public/assets/
// The root files are never modified, so a re-export flows through with one command.
import { copyFileSync, existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const ui = join(root, "apps", "ui");

function copyDir(from: string, to: string, filter: (name: string) => boolean): string[] {
  if (!existsSync(from)) throw new Error(`Missing ${from}. Is the Claude Design export at the repo root?`);
  mkdirSync(to, { recursive: true });
  const copied: string[] = [];
  for (const name of readdirSync(from)) {
    if (!filter(name)) continue;
    copyFileSync(join(from, name), join(to, name));
    copied.push(name);
  }
  return copied;
}

const tokensSrc = join(root, "headwaters-tokens.css");
const tokensDst = join(ui, "src", "styles", "headwaters-tokens.css");
const css = readFileSync(tokensSrc, "utf8");
const rewritten = css.replace(/url\((["']?)fonts\//g, "url($1/fonts/");
const fontRefs = (rewritten.match(/url\(["']?\/fonts\//g) ?? []).length;
mkdirSync(dirname(tokensDst), { recursive: true });
writeFileSync(
  tokensDst,
  `/* GENERATED by \`pnpm design:sync\` from /headwaters-tokens.css. Do not edit; re-export from Claude Design. */\n${rewritten}`,
);

const fonts = copyDir(join(root, "fonts"), join(ui, "public", "fonts"), (n) => /\.(ttf|woff2?|otf|txt)$/i.test(n));
const assets = copyDir(join(root, "assets"), join(ui, "public", "assets"), (n) => /\.(svg|png|webp|ico)$/i.test(n));

console.log(`design:sync  tokens → apps/ui/src/styles/headwaters-tokens.css (${fontRefs} font urls rewritten)`);
console.log(`design:sync  fonts  → apps/ui/public/fonts/ (${fonts.join(", ")})`);
console.log(`design:sync  assets → apps/ui/public/assets/ (${assets.join(", ")})`);
